# String Filehandeling
# part_1
text = input("Enter text: ")

print("Original:", text)
print("Uppercase:", text.upper())
print("First letter uppercase:", text.capitalize())
print("Each word uppercase:", text.title())


# part_2
text = input("Enter text: ")

print("Original:", text)
print("Lowercase:", text.lower())
print("Swap case:", text.swapcase())

