# Tuple Type Casting
# String to Tuple

a = "python"
print(tuple(a))

# List to Tuple

b = ["python", "JAVA", "C++", "HTML"]
print(tuple(b))

# Set to Tuple

c = {"blue", "pink", "red", "black"}
print(tuple(c))

# Tuple to List

d = ("python", "JAVA", "C++", "HTML")
print(list(d))

# Tuple to Set

e = ("blue", "pink", "red", "black")
print(set(e))