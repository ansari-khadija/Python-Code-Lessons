# List Type Casting
# String to List

a = "python"
print(list(a))

# Tuple to List

b = ("python", "JAVA", "C++", "HTML")
print(list(b))

# Set to List

c = {"blue", "pink", "red", "black"}
print(list(c))

# List to Tuple

d = ["python", "JAVA", "C++", "HTML"]
print(tuple(d))

# List to Set

e = ["blue", "pink", "red", "black"]
print(set(e))